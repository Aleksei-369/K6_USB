function [ LUTxx, LUTyy, status] = UpdateLUT( len, xx, yy)
status = 0;
LUTxx = xx; % коды N
LUTyy = yy; % толщины

% проверим монотонность xx, yy
if any( diff(xx) <= 0) % коды строго возрастают
    status = 1;
end

if any( diff(yy) >= 0) % толщины строго убывают
    status = 1;
end

if status == 0
    q = len - length(xx); % количество недостоющих точек
    if q > 0
        % мой старый вариант
        % xx_pad = ( -q : 1 : -1) * 0.1 + xx(1); % коды
        % yy_pad = ( q : -1 : 1) * 0.1 + yy(1); % толщины
        % LUTxx = [ xx_pad xx];
        % LUTyy = [ yy_pad yy];

        % Берем параметры САМОГО ПЕРВОГО реального сегмента (между точкой 1 и 2)
        % dx — шаг кодов (положительный), dy — шаг толщин (отрицательный)
        dx = xx(2) - xx(1); 
        dy = yy(2) - yy(1); 
        
        % Мелко нарезаем этот крайний отрезок на (q + 1) под-сегментов
        sub_dx = dx / (q + 1);
        sub_dy = dy / (q + 1);
        
        % 🌟 ГЛАВНЫЙ МАНЕВР: Шагаем ВПРАВО от xx(1) строго внутри сегмента!
        % (1:q) создает ровную гребенку шагов. Точки ложатся идеально на прямую.
        xx_pad = xx(1) + (1:q) * sub_dx;
        yy_pad = yy(1) + (1:q) * sub_dy;
        
        % Собираем монолитный 25-точечный массив. 
        % Вставляем наш сгенерированный хвост СТРОГО между первой и второй точкой!
        LUTxx = [xx(1), xx_pad, xx(2:end)];
        LUTyy = [yy(1), yy_pad, yy(2:end)];
    end
end

end